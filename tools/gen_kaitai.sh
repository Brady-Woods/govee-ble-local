#!/usr/bin/env bash
#
# Compile spec/*.ksy with the Kaitai Struct compiler (ksc 0.11.x).
#
#   bash tools/gen_kaitai.sh                       # read-write classes -> src/govee_ble_local/_generated/
#   bash tools/gen_kaitai.sh --out D               # ... into directory D instead
#   bash tools/gen_kaitai.sh --read-only --out D   # read-only readers (auto-read) into D, for scratch use
#
# The generated classes are Kaitai 0.11 READ-WRITE classes (ReadWriteKaitaiStruct): the library
# both parses frames with them (from_bytes() / Cls(..., stream), then an explicit _read()) and
# writes every frame with them (wire/build.py: _check(), then _write()). They are a build product:
# gitignored, never committed, and generated by every build (the in-tree PEP 517 backend in
# _build_backend/ runs this script before setuptools builds an sdist, a wheel or an editable
# install; the sdist and wheel ship the result). --read-write is the default and kept as an alias.
#
# Compilers. ksc is published in two builds that produce the same Python:
#   - the JVM CLI (`kaitai-struct-compiler`, e.g. `brew install kaitai-struct-compiler`, which
#     brings its own OpenJDK). The only one that exposes --read-write, so every build needs it.
#   - the pure-JS build on npm, driven by tools/kaitai_gen.js. Its compile() API has no
#     read-write switch, so it is used only for --read-only builds when no JVM ksc is found.
# Both builds give byte-identical read-only output on ksc 0.11 (checked 2026-10-16).
# Override the JVM compiler with KSC=/path/to/kaitai-struct-compiler.
#
# JS fallback, one-time userland setup (no admin/JVM required) if you have neither Node nor
# the compiler packages:
#   VER=$(curl -s https://nodejs.org/dist/index.json | python3 -c \
#     "import sys,json;print([x for x in json.load(sys.stdin) if x['lts']][0]['version'])")
#   curl -sL "https://nodejs.org/dist/$VER/node-$VER-darwin-arm64.tar.gz" | tar -xz -C .toolchain/
#   echo ".toolchain/node-$VER-darwin-arm64" > .toolchain/node_dir.txt
#   PATH="$PWD/$(cat .toolchain/node_dir.txt)/bin:$PATH" \
#     npm --prefix .toolchain/ksc install kaitai-struct-compiler@0.11.0 js-yaml
set -euo pipefail
cd "$(dirname "$0")/.."

# Every spec/*.ksy, compiled in ONE call so the files' imports resolve (`--python-package .` makes them
# relative imports inside the generated package): the same set spec/checks/run.sh gates.
shopt -s nullglob
KSY_FILES=()
for f in spec/*.ksy; do KSY_FILES+=("$(basename "$f")"); done
shopt -u nullglob
[ ${#KSY_FILES[@]} -gt 0 ] || { echo "error: no spec/*.ksy" >&2; exit 1; }
LIBRARY_DIR=src/govee_ble_local/_generated   # gitignored: a build product
KSC_SERIES="0.11"   # the generated classes and the kaitaistruct>=0.11 runtime floor

mode=readwrite
out=""
while [ $# -gt 0 ]; do
  case "$1" in
    --read-write|-w) mode=readwrite ;;
    --read-only) mode=readonly ;;
    --out) [ $# -ge 2 ] || { echo "error: --out needs a directory" >&2; exit 2; }; out="$2"; shift ;;
    -h|--help) sed -n '2,8p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) echo "error: unknown argument '$1' (see --help)" >&2; exit 2 ;;
  esac
  shift
done

# Find a JVM ksc of the pinned series; prints its path, or nothing.
find_jvm_ksc() {
  local cand path ver
  for cand in ${KSC:+"$KSC"} kaitai-struct-compiler ksc; do
    path=$(command -v "$cand" 2>/dev/null) || continue
    ver=$("$path" --version 2>/dev/null | head -1) || continue
    case "$ver" in
      "kaitai-struct-compiler $KSC_SERIES"|"kaitai-struct-compiler $KSC_SERIES".*) echo "$path"; return 0 ;;
      kaitai-struct-compiler*) echo "warning: ignoring $path ($ver); this repo pins ksc $KSC_SERIES.x" >&2 ;;
    esac
  done
  return 1
}

# compile_with_jvm <outdir> [extra ksc args...]
# The JVM CLI prints ksy style-guide warnings (naming hints) on every run; show a count unless
# VERBOSE=1, and the full log whenever the compile fails.
compile_with_jvm() {
  local dest=$1; shift
  local log rc=0 nwarn
  mkdir -p "$dest"
  dest=$(cd "$dest" && pwd)
  log=$(mktemp "${TMPDIR:-/tmp}/gen_kaitai_ksc.XXXXXX")
  ( cd spec && "$KSC_BIN" -t python --python-package . "$@" --outdir "$dest" "${KSY_FILES[@]}" ) \
    >"$log" 2>&1 || rc=$?
  if [ "$rc" -ne 0 ] || [ "${VERBOSE:-0}" = 1 ]; then
    cat "$log" >&2
  else
    nwarn=$(grep -c 'warning:' "$log" || true)
    [ "$nwarn" -eq 0 ] || echo "   ($nwarn ksy style warnings; VERBOSE=1 to show them)"
  fi
  rm -f "$log"
  return "$rc"
}

# compile_with_js <outdir>   (read-only only)
compile_with_js() {
  if [ -f .toolchain/node_dir.txt ] && [ -x "$(cat .toolchain/node_dir.txt)/bin/node" ]; then
    export PATH="$PWD/$(cat .toolchain/node_dir.txt)/bin:$PATH"
  fi
  if ! command -v node >/dev/null 2>&1; then
    echo "error: no JVM kaitai-struct-compiler $KSC_SERIES.x and no 'node' for the JS fallback." >&2
    echo "       Install one: 'brew install kaitai-struct-compiler', or the userland Node setup" >&2
    echo "       at the top of this script." >&2
    exit 1
  fi
  if [ ! -d .toolchain/ksc/node_modules/kaitai-struct-compiler ]; then
    echo ">> installing kaitai-struct-compiler@0.11.0 + js-yaml into .toolchain/ksc"
    mkdir -p .toolchain/ksc
    [ -f .toolchain/ksc/package.json ] || echo '{"name":"ksc-scratch","private":true}' > .toolchain/ksc/package.json
    ( cd .toolchain/ksc && npm install --no-audit --no-fund --loglevel=error kaitai-struct-compiler@0.11.0 js-yaml )
  fi
  NODE_PATH="$PWD/.toolchain/ksc/node_modules" node tools/kaitai_gen.js "$1" "${KSY_FILES[@]}"
}

KSC_BIN=$(find_jvm_ksc || true)

need_jvm_ksc() {
  if [ -z "$KSC_BIN" ]; then
    echo "error: the library's classes are read-write, which needs the JVM kaitai-struct-compiler" >&2
    echo "       $KSC_SERIES.x (the npm build's compile() API can't generate read-write code). Install" >&2
    echo "       it ('brew install kaitai-struct-compiler', or on Debian/Ubuntu 'bash scripts/install_ksc.sh')," >&2
    echo "       or point KSC= at one. To just use the library, install the released package from PyPI," >&2
    echo "       which ships the classes." >&2
    exit 1
  fi
}

case "$mode" in
  readonly)
    if [ -z "$out" ] || [ "$out" = "$LIBRARY_DIR" ]; then
      echo "error: --read-only needs --out to a scratch directory; the library's classes are read-write" >&2
      exit 2
    fi
    dest=$out
    if [ -n "$KSC_BIN" ]; then
      echo ">> compiling read-only readers with $KSC_BIN ($("$KSC_BIN" --version | head -1))"
      compile_with_jvm "$dest"
    else
      echo ">> no JVM ksc $KSC_SERIES.x found; using the pure-JS compiler (read-only)"
      compile_with_js "$dest"
    fi
    echo ">> done: $dest/ (read-only: from_bytes() reads)"
    ;;
  readwrite)
    need_jvm_ksc
    dest=${out:-$LIBRARY_DIR}
    # The library dir is untracked, so git can't show a leftover module in it, and the sdist and wheel
    # would ship one: start it empty, so it holds exactly the compiler's output plus __init__.py.
    [ "$dest" != "$LIBRARY_DIR" ] || rm -rf "$LIBRARY_DIR"
    echo ">> compiling read-write classes with $KSC_BIN ($("$KSC_BIN" --version | head -1))"
    compile_with_jvm "$dest" --read-write
    # Keep the generated dir an importable package.
    if [ "$dest" = "$LIBRARY_DIR" ] && [ ! -f "$dest/__init__.py" ]; then
      echo '"""Kaitai-generated read-write classes (regenerate via tools/gen_kaitai.sh)."""' > "$dest/__init__.py"
    fi
    echo ">> done: $dest/ (needs kaitaistruct>=0.11; call _read() after from_bytes())"
    ;;
esac
